# در نسخهٔ واقعی، مدیر همین جدول را پر می‌کند.
# همهٔ طرح‌ها «کاربر نامحدود» دارند.

# هر طرح: کد، مدت به ماه، قیمت به تومان، نام نمایشی، توضیح
