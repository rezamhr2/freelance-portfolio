def format_toman(amount: int) -> str:
    """عدد را با جداکننده‌ی هزارگان و واحد تومان برمی‌گرداند."""
    return f"{amount:,} تومان"


def get_plan(code: str) -> dict | None:
    """یک طرح را با کد پیدا می‌کند؛ کد نامعتبر None می‌دهد."""
    return PLANS.get((code or "").strip().lower())


def format_plans() -> str:
    """فهرست همه‌ی طرح‌ها با مدت و قیمت — همان جدول قیمت درون‌چتی."""
    lines = ["📋 طرح‌های اشتراک سپهر:", ""]
    for code, plan in PLANS.items():
        lines.append(
            f"• {plan['name']} — {format_toman(plan['price_toman'])} "
            f"(کد: {code})"
        )
    lines.append("")
    lines.append("همه‌ی طرح‌ها کاربر نامحدود دارند.")
    lines.append("برای دیدن جزئیات و خرید، روی یک طرح بزنید.")
    return "\n".join(lines)


def format_plan(code: str) -> str:
    """جزئیات یک طرح؛ کد نامعتبر پیام راهنما می‌دهد."""
    plan = get_plan(code)
    if plan is None:
        valid = "، ".join(PLANS.keys())
        return f"❌ طرح «{code}» پیدا نشد. طرح‌های معتبر: {valid}"
    return (
        f"📋 {plan['name']}\n"
        f"مدت: {plan['months']} ماه\n"
        f"کاربر: نامحدود\n"
        f"قیمت: {format_toman(plan['price_toman'])}\n"
        f"{plan['desc']}"
    )
